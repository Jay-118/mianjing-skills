SUFFIXES = ["面经", "面试", "面试题", "一面", "二面", "实习面试"]


def build_matrix(extra=None, with_company=True, max_kw=48, with_agent=True):
    """生成关键词矩阵。

    Args:
        extra: 用户追加的方向关键词 list
        with_company: 是否铺开公司线
        max_kw: 上限，防止请求量爆炸
        with_agent: 是否加入 Agent 生态线（AI 安全岗建议开，默认开）
    Returns:
        list[str] 去重后的查询词
    """
    out = []

    # 岗位线 × 面经后缀
    for r in ROLE_WORDS:
        out.append(f"{r} 面经")
    for r in ROLE_WORDS[:6]:
        out.append(f"{r} 面试题")

    # 技术考点线：只配「面试」，避免纯技术文章噪声
    for t in TECH_POINTS:
        out.append(f"{t} 面试")

    # AI 安全专线
    for t in AI_SEC_POINTS:
        out.append(f"{t} 面试")

    # Agent 生态线（AI 安全岗高频考点，小红书密度最高）
    if with_agent:
        for t in AGENT_ECOSYSTEM:
            out.append(f"{t} 面试")

    # 公司线
    if with_company:
        for c in COMPANIES:
            out.append(f"{c} 安全 面经")

    if extra:
        for e in extra:
            e = e.strip()
            if not e:
                continue
            out.append(e if any(s in e for s in SUFFIXES) else f"{e} 面经")

    # 去重保序
    seen, uniq = set(), []
    for q in out:
        if q not in seen:
            seen.add(q)
            uniq.append(q)
    return uniq[:max_kw]


